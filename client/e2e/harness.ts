/** What the e2e page (`page/harness.js`) puts on `window`, for the specs. */

import type { Divergence, DocumentKey, Transfer } from '../src/index.js';

/** What every device shows of its engine. */
export interface DeviceState {
	status: string;
	via: string | null;
	error: string | null;
	transfer: Transfer | null;
	/** Every transfer the engine told, in order, without repeats. */
	transfers: (Transfer | null)[];
	diverged: Divergence[];
}

interface Controls {
	pair(code: string): Promise<string>;
	/** The app hidden and shown again: the engine reconnects. */
	reconnect(): void;
	syncNow(): Promise<void>;
	resumeTransfer(): Promise<void>;
	restartTransfer(): Promise<void>;
	/** Answers a divergence; `resolved` or the error code. */
	resolve(serverId: string, keep: 'main' | 'subordinate'): Promise<string>;
}

/** A device of the notes app: the built package's engine over a set of notes, merged as a union. */
export interface Device extends Controls {
	state: DeviceState & { notes: string[] };
	add(note: string): void;
}

/** A file of the files app: text, or `size` generated bytes from `seed`, each 1 MiB slow to read. */
export type FileSpec =
	| { key: DocumentKey; text: string }
	| { key: DocumentKey; size: number; seed: number; delayMs?: number };

/** A device of an app with any number of documents, one per file. */
export interface FilesDevice extends Controls {
	state: DeviceState & { lists: number };
	write(file: FileSpec): void;
	remove(key: DocumentKey): void;
	/** The files held: a text file as its text, any other as `<n> bytes`. */
	files(): Record<string, string>;
}

declare global {
	interface Window {
		harness: {
			createDevice(notes: string[]): Device;
			createFilesDevice(files?: FileSpec[]): FilesDevice;
			pairAs(app: string, code: string): Promise<string>;
			documents(app: string, code: string, size: number): Promise<Record<string, unknown> | string>;
		};
		device: Device;
		files: FilesDevice;
	}
}
