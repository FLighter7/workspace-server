// pickLanguage returns the language of messages that an Accept-Language
// header prefers most, matching on the primary subtag ("ru-RU" is "ru"), or
// English when it prefers none of them. Equal weights keep the header's
// order; a weight of 0 or one that does not parse rules a language out.
func pickLanguage(header string) string {
	best, bestQ := defaultLanguage, 0.0
	for _, item := range strings.Split(header, ",") {
		tag, params, _ := strings.Cut(item, ";")
		primary, _, _ := strings.Cut(strings.ToLower(strings.TrimSpace(tag)), "-")
		if primary == "*" {
			primary = defaultLanguage
		}
		if _, ok := messages[primary]; !ok {
			continue
		}
		q, ok := weight(params)
		if !ok || q <= bestQ {
			continue
		}
		best, bestQ = primary, q
	}
	return best
}

// weight returns the q parameter of an Accept-Language item, 1 when absent.
// It reports false when q does not parse or lies outside 0-1.
func weight(params string) (float64, bool) {
	for _, p := range strings.Split(params, ";") {
		name, value, _ := strings.Cut(strings.TrimSpace(p), "=")
		if strings.TrimSpace(name) != "q" {
			continue
		}
		q, err := strconv.ParseFloat(strings.TrimSpace(value), 64)
		if err != nil || !(q >= 0 && q <= 1) {
			return 0, false
		}
		return q, true
	}
	return 1, true
}
